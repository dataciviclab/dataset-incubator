-- clean.sql — OpenCoesione Soggetti: beneficiari fondi coesione
-- Input: raw_input (soggetti.parquet)
-- Output: soggetti puliti con CF, ruolo, forma giuridica, comune

SELECT
  COD_LOCALE_PROGETTO,
  SOGG_COD_RUOLO,
  SOGG_DESCR_RUOLO,
  OC_CODICE_FISCALE_SOGG,
  OC_DENOMINAZIONE_SOGG,
  COD_FORMA_GIURIDICA_SOGG,
  DESCR_FORMA_GIURIDICA_SOGG,
  COD_COMUNE_SEDE_SOGG,
  INDIRIZZO_SOGG,
  CAP_SOGG,
  COD_ATECO_SOGG,
  DESCRIZIONE_ATECO_SOGG,
  COD_DIMENSIONE_SOGG,
  DESCR_DIMENSIONE_SOGG,
  CODICE_FISCALE_SOGGETTO,
  DENOMINAZIONE_SOGGETTO
FROM raw_input
WHERE COD_LOCALE_PROGETTO IS NOT NULL
  AND OC_CODICE_FISCALE_SOGG IS NOT NULL
  AND trim(OC_CODICE_FISCALE_SOGG) <> ''
