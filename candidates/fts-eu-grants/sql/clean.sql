    cast_int(cast_bigint(anno)) AS anno,
    budget::VARCHAR AS budget,
    rif_impegno_giuridico::VARCHAR AS rif_impegno_giuridico,
    rif_bilancio::VARCHAR AS rif_bilancio,
    beneficiario_nome::VARCHAR AS beneficiario_nome,
