    fonte_dettaglio::VARCHAR AS fonte_dettaglio,
    tipo_spesa::VARCHAR AS tipo_spesa,
    oggetto_contributo::VARCHAR AS oggetto_contributo,
    dipartimento_responsabile::VARCHAR AS dipartimento_responsabile,
