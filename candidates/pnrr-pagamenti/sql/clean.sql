SELECT
    CAST("Codice Univoco Submisura" AS VARCHAR) AS codice_univoco_submisura,
    CAST("Descrizione Submisura" AS VARCHAR) AS descrizione_submisura,
    NULLIF(TRIM(CAST("CUP" AS VARCHAR)), '') AS cup,
    NULLIF(TRIM(CAST("Codice Locale Progetto" AS VARCHAR)), '') AS codice_locale_progetto,
    CAST("Finanziamento Totale" AS DOUBLE) AS finanziamento_totale,
    CAST("Finanziamento PNRR" AS DOUBLE) AS finanziamento_pnrr,
    CAST("Pagamento Totale" AS DOUBLE) AS pagamento_totale,
    CAST("Pagamento PNRR" AS DOUBLE) AS pagamento_pnrr,
    CAST("Pagamento - Stato" AS DOUBLE) AS pagamento_stato,
    CAST("Pagamento Stato - Bilancio" AS DOUBLE) AS pagamento_stato_bilancio,
    CAST("Pagamento Stato - FOI" AS DOUBLE) AS pagamento_stato_foi,
    CAST("Pagamento Prosecuzione Opere Pubbliche - FPOP" AS DOUBLE) AS pagamento_fpop,
    CAST("Pagamento UE (Diverso da PNRR)" AS DOUBLE) AS pagamento_ue,
    CAST("Pagamento Regione" AS DOUBLE) AS pagamento_regione,
    CAST("Pagamento Provincia" AS DOUBLE) AS pagamento_provincia,
    CAST("Pagamento Comune" AS DOUBLE) AS pagamento_comune,
    CAST("Pagamento Altro Pubblico" AS DOUBLE) AS pagamento_altro_pubblico,
    CAST("Pagamento Privato" AS DOUBLE) AS pagamento_privato,
    CAST("Pagamento da Reperire" AS DOUBLE) AS pagamento_da_reperire,
    CAST("Pagamento PNC" AS DOUBLE) AS pagamento_pnc,
    CAST("Pagamento Altri Fondi" AS DOUBLE) AS pagamento_altri_fondi,
    TRY_STRPTIME(CAST("Data di Estrazione" AS VARCHAR), '%d/%m/%Y') AS data_estrazione,
    CAST({year} AS INTEGER) AS anno_estrazione
FROM raw_input
